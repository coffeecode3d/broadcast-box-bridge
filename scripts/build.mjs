#!/usr/bin/env node
import { build } from "esbuild";
import { createHash } from "crypto";
import { existsSync } from "fs";
import { cp, mkdir, readFile, rm, writeFile } from "fs/promises";
import { homedir } from "os";
import { dirname, join, resolve } from "path";
import { spawn } from "child_process";
import { fileURLToPath } from "url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const has = flag => args.includes(flag);

const equicordDir = process.env.EQUICORD_DIR || join(homedir(), "Equicord");
const betterDiscordDir = process.env.BD_PLUGIN_DIR || join(homedir(), ".config/BetterDiscord/plugins");
const distDir = join(root, "dist");
const pluginFolderName = "broadcastBoxBridge";

const pluginFiles = ["index.ts", "native.ts", "host.ts"];
const pluginDirs = ["core", "node"];

async function buildHelper() {
    await mkdir(distDir, { recursive: true });
    const outfile = join(distDir, "BroadcastBoxBridge.helper.cjs");
    await build({
        entryPoints: [join(root, "betterdiscord/helper-entry.ts")],
        outfile,
        bundle: true,
        format: "cjs",
        platform: "node",
        target: "node20",
        charset: "utf8",
        legalComments: "none",
        sourcemap: false,
        minify: false,
        logLevel: "warning"
    });
    const source = await readFile(outfile, "utf8");
    const version = createHash("sha256").update(source).digest("hex").slice(0, 16);
    const generated = `// Generated by scripts/build.mjs. Do not edit.
export const HELPER_VERSION = ${JSON.stringify(version)};
export const HELPER_SOURCE = ${JSON.stringify(source)};
`;
    await writeFile(join(root, "betterdiscord/helperSource.ts"), generated);
    console.log(`[build] BetterDiscord helper -> ${outfile} (${version})`);
    return version;
}

async function buildBetterDiscord() {
    await buildHelper();
    await mkdir(distDir, { recursive: true });
    const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8"));

    const banner = `/**
 * @name BroadcastBoxBridge
 * @author BroadcastBoxBridge contributors
 * @description Publish your screen to a self-hosted Broadcast Box instance and watch other members' streams inside Discord.
 * @version ${pkg.version}
 * @donate false
 * @patreon false
 */
`;

    const outfile = join(distDir, "BroadcastBoxBridge.plugin.js");
    await build({
        entryPoints: [join(root, "betterdiscord/index.ts")],
        outfile,
        bundle: true,
        format: "iife",
        globalName: "BroadcastBoxBridgeBundle",
        platform: "node",
        target: "node20",
        external: ["electron"],
        charset: "utf8",
        legalComments: "none",
        sourcemap: false,
        minify: false,
        banner: { js: banner },
        footer: { js: "\nmodule.exports = BroadcastBoxBridgeBundle.default;\n" },
        logLevel: "warning"
    });

    console.log(`[build] BetterDiscord plugin -> ${outfile}`);
    return outfile;
}

async function installBetterDiscord(bundle) {
    await mkdir(betterDiscordDir, { recursive: true });
    const destination = join(betterDiscordDir, "BroadcastBoxBridge.plugin.js");
    await cp(bundle, destination);
    console.log(`[build] installed BetterDiscord plugin -> ${destination}`);
    console.log("[build] enable it in BetterDiscord's plugin list (Settings > Plugins).");
}

async function syncEquicord() {
    if (!existsSync(join(equicordDir, "src"))) {
        console.log(`[build] Equicord checkout not found at ${equicordDir}; skipping userplugin sync.`);
        console.log("[build] Set EQUICORD_DIR to your Equicord checkout to enable it.");
        return;
    }
    const destination = join(equicordDir, "src/userplugins", pluginFolderName);
    await rm(destination, { recursive: true, force: true });
    await mkdir(destination, { recursive: true });

    for (const file of pluginFiles) {
        await cp(join(root, file), join(destination, file));
    }
    for (const dir of pluginDirs) {
        await cp(join(root, dir), join(destination, dir), { recursive: true });
    }

    console.log(`[build] Equicord userplugin -> ${destination}`);
    console.log("[build] next:");
    console.log(`  cd ${equicordDir}`);
    console.log("  pnpm build");
    console.log("  pnpm inject --install");
}

function run(command, commandArgs, cwd) {
    return new Promise((resolvePromise, reject) => {
        const child = spawn(command, commandArgs, { cwd, stdio: "inherit", shell: false });
        child.on("exit", code =>
            code === 0 ? resolvePromise() : reject(new Error(`${command} exited with code ${code}`))
        );
        child.on("error", reject);
    });
}

const wantsBD = has("--bd") || has("--install-bd") || !has("--install-equicord");
const wantsEquicord = has("--install-equicord") || !has("--bd");

try {
    let bundle = null;
    if (wantsBD) bundle = await buildBetterDiscord();
    if (wantsEquicord) await syncEquicord();
    if (has("--install-bd") && bundle) await installBetterDiscord(bundle);
    if (has("--build-equicord")) {
        console.log("[build] running the Equicord build…");
        await run("pnpm", ["build"], equicordDir);
        console.log("[build] Equicord build finished. Restart Discord after injecting.");
    }
    if (has("--inject-equicord")) {
        console.log("[build] injecting Equicord…");
        await run("pnpm", ["inject", "--install"], equicordDir);
    }
} catch (error) {
    console.error(`[build] ${error instanceof Error ? error.message : error}`);
    process.exitCode = 1;
}
